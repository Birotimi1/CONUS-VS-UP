function validate_configuration(par)
% Fail before starting expensive solvers if an RJ prior/proposal is invalid.
assert(isequal(par.inv.datatypes,{'hvsr','ellip','cph','ugr','rf'}) || ...
    isequal(par.inv.datatypes,{'hvsr','ellip','cph','ugr','rf','rf_sp'}), ...
    'thbi:config','Expected four surface observables and Ps, optionally Sp.');
nd=numel(par.inv.datatypes);
assert(isequal(par.mod.zone_fields,{'sedmparm','crustmparm','mantmparm'}),'thbi:config','Expected three named zones.');
%% =================== PARAMETER SHAPES AND FINITE VALUES ===================
for name={'kmin','kmax','min_fraction','vsmin','vsmax'}
    x=par.mod.(name{1});
    assert(isequal(size(x),[1 3]) && isreal(x) && all(isfinite(x)), ...
        'thbi:config','par.mod.%s must be a finite real 1-by-3 row.',name{1});
end
for name={'boundary_lower','boundary_upper','halfspace_bounds'}
    x=par.mod.(name{1});
    assert(isequal(size(x),[1 2]) && isreal(x) && all(isfinite(x)), ...
        'thbi:config','par.mod.%s must be a finite real 1-by-2 row.',name{1});
end
for name={'log_center','log_width','lower','upper'}
    x=par.mod.noise.(name{1});
    assert(isequal(size(x),[nd 1]) && isreal(x) && all(isfinite(x)), ...
        'thbi:config','par.mod.noise.%s must match the number of likelihood blocks.',name{1});
end
assert(isscalar(par.mod.maxz) && isreal(par.mod.maxz) && isfinite(par.mod.maxz), ...
    'thbi:config','Maximum depth must be a finite real scalar.');
assert(isequal(size(par.conditions.monotonic),[1 3]),'thbi:config','Set one monotonicity flag per zone.');
assert(isscalar(par.conditions.max_moho_fraction) && par.conditions.max_moho_fraction>=0, ...
    'thbi:config','Moho contrast limit must be nonnegative (Inf disables it).');
assert(isscalar(par.conditions.max_moho_jump) && par.conditions.max_moho_jump>=0, ...
    'thbi:config','Absolute Moho contrast limit must be nonnegative (Inf disables it).');

%% =================== NORMALIZABLE MODEL PRIORS ===================
assert(all(par.mod.kmin>=1 & par.mod.kmax>=par.mod.kmin) && ...
    all(mod([par.mod.kmin par.mod.kmax],1)==0),'thbi:config','Invalid count limits.');
assert(all(par.mod.min_fraction>0 & par.mod.kmax.*par.mod.min_fraction<1),'thbi:config','Invalid minimum fractions.');
assert(all(par.mod.vsmin>0 & par.mod.vsmax>par.mod.vsmin),'thbi:config','Invalid velocity bounds.');
assert(all(par.mod.boundary_upper>par.mod.boundary_lower) && ...
    par.mod.boundary_lower(1)>0 && par.mod.boundary_upper(1)<par.mod.boundary_lower(2) && ...
    par.mod.boundary_upper(2)<par.mod.maxz,'thbi:config','Boundary ranges must be ordered and disjoint.');
assert(par.mod.halfspace_bounds(1)>0 && diff(par.mod.halfspace_bounds)>0,'thbi:config','Invalid half-space prior.');
p=par.proposal.probability; pz=par.proposal.zone_probability;
assert(isequal(par.proposal.names(1:6),{'velocity','interface','boundary','birth','death','noise'}), ...
    'thbi:config','Move ordering changed.');
assert(isequal(size(p),[1 numel(par.proposal.names)]) && isreal(p) && all(p>=0 & isfinite(p)) && abs(sum(p)-1)<1e-12 && ...
    isequal(size(pz),[1 3]) && isreal(pz) && all(pz>0 & isfinite(pz)) && abs(sum(pz)-1)<1e-12, ...
    'thbi:config','Invalid move/zone probabilities.');
assert((p(4)>0)==(p(5)>0),'thbi:config','Birth and death must both be enabled or both disabled.');
for name={'vs_step','interface_step','birth_vs_sigma'}
    assert(isequal(size(par.proposal.(name{1})),[1 3]), ...
        'thbi:config','Set three zone proposal scales for %s.',name{1});
end
assert(isequal(size(par.proposal.boundary_step),[1 2]) && ...
    isscalar(par.proposal.halfspace_step) && isscalar(par.proposal.noise_step), ...
    'thbi:config','Expected two boundary scales and scalar half-space/noise scales.');
scales=[par.proposal.vs_step par.proposal.interface_step par.proposal.boundary_step ...
    par.proposal.birth_vs_sigma par.proposal.halfspace_step par.proposal.noise_step];
assert(isreal(scales) && all(isfinite(scales) & scales>0), ...
    'thbi:config','Proposal scales must be finite and positive.');
assert(par.proposal.halfspace_probability>0 && par.proposal.halfspace_probability<1, ...
    'thbi:config','Half-space selection probability must be between 0 and 1.');
assert(any(strcmp(par.mod.count_prior,{'jeffreys','uniform'})),'thbi:config','Invalid count prior.');
assert(all(par.mod.noise.log_width>0) && all(par.mod.noise.upper>par.mod.noise.lower), ...
    'thbi:config','Invalid noise prior.');
assert(any(strcmp(par.mod.start.method,{'reference','prior'})), ...
    'thbi:config','Start method must be reference or prior.');
if isfield(par.proposal,'birth_broad_probability')
    w=par.proposal.birth_broad_probability; s=par.proposal.birth_vs_sigma_broad;
    assert(isscalar(w) && isreal(w) && isfinite(w) && w>=0 && w<1 && ...
        isequal(size(s),[1 3]) && isreal(s) && all(isfinite(s) & s>0), ...
        'thbi:config','Invalid Gaussian birth mixture.');
end
if isfield(par.proposal,'dr')
    assert(islogical(par.proposal.dr.enabled) && isscalar(par.proposal.dr.enabled) && ...
        isscalar(par.proposal.dr.scale) && isfinite(par.proposal.dr.scale) && ...
        par.proposal.dr.scale>0 && par.proposal.dr.scale<1, ...
        'thbi:config','DR must have a logical flag and a fixed shrink factor in (0,1).');
    assert(isfield(par.proposal.dr,'mode') && ...
        any(strcmp(par.proposal.dr.mode,{'fixed_scalar','layered_path','targeted_layered'})), ...
        'thbi:config','Choose fixed_scalar, layered_path or targeted_layered delayed rejection.');
    if strcmp(par.proposal.dr.mode,'targeted_layered')
        w=par.proposal.dr.same_zone_weight;
        assert(isvector(w) && any(numel(w)==[1 3]) && isreal(w) && ...
            all(isfinite(w) & w>=0 & w<1), ...
            'thbi:config','Use one or three same-zone weights in [0,1), preserving reverse support.');
    end
end
if isfield(par.mod,'vpvs_bounds')
    assert(any(strcmp(par.mod.anisotropy,{'isotropic','vti'})),'thbi:config','Unknown anisotropy mode.');
    assert(strcmp(par.mod.anisotropy,'vti')==isfield(par.mod,'xi_bounds'), ...
        'thbi:config','VTI mode requires the full xi state/prior configuration.');
    assert(isequal(par.proposal.names(7:10),{'vpvs','boundary_mean','boundary_jump','moho_hk'}) && ...
        isequal(size(par.mod.vpvs_bounds),[1 2]) && par.mod.vpvs_bounds(1)>sqrt(4/3) && ...
        diff(par.mod.vpvs_bounds)>0,'thbi:config','Invalid crustal Vp/Vs prior/moves.');
    assert(strcmp(par.proposal.dr.mode,'layered_path') && par.proposal.dr.enabled, ...
        'thbi:config','Extended moves require the audited full random-path DR mode.');
    scales=[par.proposal.vpvs_step par.proposal.coupled_vs_step par.proposal.moho_hk_step];
    assert(all(isfinite(scales) & scales>0),'thbi:config','Invalid extended move scales.');
    assert(isequal(size(par.mod.noise.log_uniform),[nd 1]) && islogical(par.mod.noise.log_uniform), ...
        'thbi:config','Specify proper log-noise priors for all data blocks.');
    assert(strcmp(par.rf.method,'hk_ccp') && nd==6,'thbi:config','Reference RF configuration missing.');
    assert(par.rf.hk.dof>0 && (isnan(par.rf.ccp.dof) || par.rf.ccp.dof>0) && par.rf.hk.min_error>0 && ...
        par.rf.hk.error_scale>0 && numel(par.rf.hk.phase_weights)==3 && ...
        all(par.rf.hk.phase_weights>=0) && sum(par.rf.hk.phase_weights)>0, ...
        'thbi:config','Invalid RF weights/degrees of freedom.');
    assert(all(diff(par.rf.hk.H_km)>0) && all(diff(par.rf.hk.kappa)>0) && ...
        min(par.rf.hk.H_km)<=par.mod.boundary_lower(2) && ...
        max(par.rf.hk.H_km)>=par.mod.boundary_upper(2) && ...
        min(par.rf.hk.kappa)<=par.mod.vpvs_bounds(1) && ...
        max(par.rf.hk.kappa)>=par.mod.vpvs_bounds(2),'thbi:config','HK grid must cover prior.');
    assert(all(diff(par.rf.ccp.depth_km)>0) && ...
        all(par.rf.hk.rayp_s_km>0),'thbi:config','Invalid RF coordinates/ray parameters.');
end
if isfield(par.mod,'xi_bounds')
    b=par.mod.xi_bounds;
    assert(strcmp(par.mod.anisotropy,'vti') && isequal(size(b),[3 2]) && ...
        all(isfinite(b(:))) && all(b(:)>0) && all(diff(b,1,2)>=0) && ...
        any(diff(b,1,2)>0) && isequal(b(1,:),[1 1]) && ...
        par.mod.psi_to_xi==-1 && par.mod.elastic_eta==1 && max(b(:))<2 && ...
        isequal(par.proposal.names(11:end),{'anisotropy'}) && par.proposal.xi_step>0, ...
        'thbi:config','Invalid linked VTI prior; surface sediments must be isotropic.');
end
%% =================== SYNTHETIC ARRAYS AND RECEIVER-FUNCTION BANDS ===================
assert(isscalar(par.synth.seed) && isreal(par.synth.seed) && isfinite(par.synth.seed) && ...
    par.synth.seed>=0 && par.synth.seed<2^32 && par.synth.seed==fix(par.synth.seed), ...
    'thbi:config','Synthetic seed must be an integer in [0,2^32).');
for name={'gamma','relative_sigma','sigma_floor'}
    x=par.synth.(name{1});
    assert(isequal(size(x),[nd 1]) && isreal(x) && all(isfinite(x) & x>=0), ...
        'thbi:config','Synthetic %s must match the likelihood blocks.',name{1});
end
assert(all(par.synth.sigma_floor>0),'thbi:config','Positive synthetic error floors required.');
for d=5:nd
    name=par.inv.datatypes{d}; cfg=par.forc.(name);
    window=par.synth.([name '_window']); stride=par.synth.([name '_stride']);
    corr=par.synth.([name '_corr_seconds']);
    vals=[cfg.dt cfg.npts cfg.delay cfg.gaussian_alpha cfg.rayp_s_km stride corr window];
    assert(isreal(vals) && all(isfinite(vals)) && cfg.dt>0 && ...
        cfg.npts>=64 && cfg.npts<=4096 && mod(log2(cfg.npts),1)==0 && ...
        cfg.delay>0 && cfg.delay<cfg.npts*cfg.dt && cfg.gaussian_alpha>0 && ...
        cfg.rayp_s_km>0 && stride>=1 && mod(stride,1)==0 && corr>=0 && ...
        isequal(size(window),[1 2]) && diff(window)>0 && ...
        window(1)>=-cfg.delay && window(2)<=(cfg.npts-1)*cfg.dt-cfg.delay, ...
        'thbi:config','Invalid RF record, window, sampling or correlation for %s.',name);
    if isfield(cfg,'period_band_s')
        bands=[cfg.period_band_s;cfg.diagnostic_period_bands_s];
        assert(size(bands,2)==2 && isreal(bands) && all(isfinite(bands(:))) && ...
            all(bands(:,1)>2*stride*cfg.dt & bands(:,2)>bands(:,1)) && ...
            cfg.npts*cfg.dt>=4*max(bands(:,2)), ...
            'thbi:config','RF bands require adequate native duration and retained sample rate.');
        % Allow the acausal filter to decay beyond BOTH ends of the data window.
        assert(window(1)+cfg.delay>=.5*max(bands(:,2)) && ...
            (cfg.npts-1)*cfg.dt-cfg.delay-window(2)>=.5*max(bands(:,2)), ...
            'thbi:config','Extend the native RF record around the selected window.');
    end
    if strcmp(name,'rf_sp')
        assert(cfg.component_gaussian_alpha>=cfg.gaussian_alpha && ...
            isfinite(cfg.component_gaussian_alpha) && cfg.water_level>0 && cfg.water_level<1 && ...
            cfg.edge_taper_fraction>=0 && cfg.edge_taper_fraction<.5, ...
            'thbi:config','Invalid Sp component/deconvolution settings.');
    end
end
%% =================== ITERATIONS AND SAVING ===================
assert(isscalar(par.res.nprior) && isreal(par.res.nprior) && isfinite(par.res.nprior) && ...
    par.res.nprior>=0 && par.res.nprior==fix(par.res.nprior), ...
    'thbi:config','Prior draw count must be a nonnegative integer (0 disables it).');
for name={'niter','burnin','nchains','seed','checkpoint_every','print_every','max_consecutive_failures'}
    x=par.inv.(name{1});
    assert(isscalar(x) && isreal(x) && isfinite(x) && x==fix(x), ...
        'thbi:config','par.inv.%s must be a finite real integer.',name{1});
end
assert(par.inv.niter>par.inv.burnin && par.inv.burnin>=0 && par.inv.nchains>=1 && ...
    all(mod([par.inv.niter par.inv.burnin par.inv.nchains],1)==0), ...
    'thbi:config','Invalid chain lengths.');
assert(par.inv.checkpoint_every>=1 && par.inv.print_every>=1,'thbi:config','Invalid save/print interval.');
assert(par.inv.seed>=1 && par.inv.seed+1009*par.inv.nchains<2^32 && ...
    par.inv.max_consecutive_failures>=1,'thbi:config','Invalid seed or failure threshold.');
stride=par.res.prediction_stride;
assert(isscalar(stride) && isreal(stride) && isfinite(stride) && stride>=0 && stride==fix(stride), ...
    'thbi:config','Prediction stride must be a nonnegative integer.');
assert(isvector(par.res.depth_km) && isreal(par.res.depth_km) && ...
    all(isfinite(par.res.depth_km)) && all(diff(par.res.depth_km)>0) && par.res.depth_km(1)>=0, ...
    'thbi:config','Output depths must be finite, nonnegative and increasing.');
assert(isvector(par.res.interface_bins_km) && numel(par.res.interface_bins_km)>=2 && ...
    isreal(par.res.interface_bins_km) && all(isfinite(par.res.interface_bins_km)) && ...
    all(diff(par.res.interface_bins_km)>0),'thbi:config','Interface bins must increase.');
end
